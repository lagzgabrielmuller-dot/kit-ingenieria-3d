def construir_parser():
    ap = argparse.ArgumentParser(prog='refrigeracion.py', description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest='cmd', required=True)

    def ref(p, req=True):
        p.add_argument('--ref', '--refrigerante', dest='ref', required=req, help='R-134a, R-410A, R-32, R-22, R-600a, R-290 o R-404A')

    def patm(p):
        p.add_argument('--patm', type=float, default=P_ATM, help='presión atmosférica en bar (1,01325 a nivel del mar)')
    p = sp.add_parser('saturacion', help='presión o temperatura de saturación')
    ref(p)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument('--t', type=float, help='temperatura en °C')
    g.add_argument('--p', type=float, help='presión manométrica (o absoluta con --absoluta)')
    p.add_argument('--unidad', choices=['bar', 'psi'], default='bar')
    p.add_argument('--absoluta', action='store_true', help='la presión dada es absoluta')
    patm(p)
    p = sp.add_parser('tabla', help='tabla presión-temperatura')
    ref(p)
    p.add_argument('--desde', type=float, default=-40)
    p.add_argument('--hasta', type=float, default=65)
    p.add_argument('--paso', type=float, default=5)
    p.add_argument('--md', action='store_true', help='en formato de tabla Markdown')
    patm(p)
    p = sp.add_parser('diagnostico', help='sobrecalentamiento, subenfriamiento y lectura orientativa')
    ref(p)
    p.add_argument('--pbaja', type=float, required=True, help='presión de baja (succión), manométrica')
