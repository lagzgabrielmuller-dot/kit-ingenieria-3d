# ------------------------------------------------------------------------------------------ interpolacion
def lagr(xs, ys, x):
    """Interpolacion cubica de Lagrange con los 4 nodos mas cercanos (xs crecientes, paso no uniforme)."""
    n = len(xs)
    lo, hi = 0, n - 1
    while hi - lo > 1:
        m = (lo + hi) // 2
        if xs[m] <= x:
            lo = m
        else:
            hi = m
    a = min(max(lo - 1, 0), n - 4)
    tot = 0.0
    for j in range(a, a + 4):
        L = 1.0
        for k in range(a, a + 4):
            if k != j:
                L *= (x - xs[k]) / (xs[j] - xs[k])
        tot += L * ys[j]
    return tot


def biseccion(f, a, b, n=80):
    fa = f(a)
    for _ in range(n):
        m = (a + b) / 2
        fm = f(m)
        if fa * fm <= 0:
            b = m
        else:
            a, fa = m, fm
    return (a + b) / 2


