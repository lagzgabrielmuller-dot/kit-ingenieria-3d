def nivel(x, rango):
    lo, hi = rango
    return 'bajo' if x < lo else ('alto' if x > hi else 'normal')


def diagnostico(R, pbaja, palta, tsuccion, tliquido, unidad='bar', patm=P_ATM, tamb=None, tinterior=None,
                expansion='txv', sh_obj=None, sc_obj=None):
    if expansion not in OBJETIVO:
        raise ValueError('--expansion: txv o capilar')
    pb, pa = a_bar(pbaja, unidad) + patm, a_bar(palta, unidad) + patm
    if pa <= pb:
        raise ValueError('la presión de alta tiene que ser mayor que la de baja')
    te_r, te_b = R.t_rocio(pb), R.t_burbuja(pb)
    tc_b, tc_r = R.t_burbuja(pa), R.t_rocio(pa)
    sh, sc = tsuccion - te_r, tc_b - tliquido
    rsh = (sh_obj - 2, sh_obj + 2) if sh_obj is not None else OBJETIVO[expansion]['sh']
    rsc = (sc_obj - 1.5, sc_obj + 1.5) if sc_obj is not None else OBJETIVO[expansion]['sc']
    ev = {'sh': nivel(sh, rsh), 'sc': nivel(sc, rsc)}
    pres = {}
    if tamb is not None:
        pres['alta'] = {'bajo': 'baja', 'normal': 'normal', 'alto': 'alta'}[nivel(tc_b - tamb, DT_COND)]
    if tinterior is not None:
        # evaporador mas frio de lo normal (dT grande) = presion de baja baja
        pres['baja'] = {'bajo': 'alta', 'normal': 'normal', 'alto': 'baja'}[nivel(tinterior - te_r, DT_EVAP)]
    u = unidad
    L = ['%s · baja %s %s man. = %s bar abs → evaporación %s °C (rocío)%s'
         % (R.nombre, n(pbaja, 2), u, n(pb, 3), n(te_r, 1), (', burbuja %s °C' % n(te_b, 1)) if R.info['mezcla'] else ''),
         '%s · alta %s %s man. = %s bar abs → condensación %s °C (burbuja)%s'
         % (' ' * len(R.nombre), n(palta, 2), u, n(pa, 3), n(tc_b, 1), (', rocío %s °C' % n(tc_r, 1)) if R.info['mezcla'] else ''),
         'Sobrecalentamiento: SH = t succión − t rocío(baja) = %s − %s = %s K → %s (rango %s a %s K%s)'
         % (n(tsuccion, 1), par(te_r, 1), n(sh, 1), ev['sh'].upper(), n(rsh[0], 0), n(rsh[1], 0),
            '' if sh_obj is not None else ', orientativo para %s: verificar con el fabricante' % ('válvula de expansión' if expansion == 'txv' else 'capilar')),
         'Subenfriamiento:    SC = t burbuja(alta) − t líquido = %s − %s = %s K → %s (rango %s a %s K%s)'
         % (n(tc_b, 1), n(tliquido, 1), n(sc, 1), ev['sc'].upper(), n(rsc[0], 1), n(rsc[1], 1),
            '' if sc_obj is not None else ', orientativo: verificar con el fabricante'),
         'Relación de compresión: %s/%s = %s' % (n(pa, 2), n(pb, 2), n(pa / pb, 2))]
    if tamb is not None:
        L.append('Condensación sobre el aire exterior: %s − %s = %s K → presión de alta %s (orientativo %s a %s K)'
                 % (n(tc_b, 1), n(tamb, 1), n(tc_b - tamb, 1), pres['alta'].upper(), n(DT_COND[0], 0), n(DT_COND[1], 0)))
    if tinterior is not None:
        L.append('Aire interior sobre la evaporación: %s − %s = %s K → presión de baja %s (orientativo %s a %s K)'
                 % (n(tinterior, 1), par(te_r, 1), n(tinterior - te_r, 1), pres['baja'].upper(), n(DT_EVAP[0], 0), n(DT_EVAP[1], 0)))
    if sh < 0:
        L.append('AVISO: SH negativo: sale líquido del evaporador (riesgo para el compresor) o la medición está mal hecha.')
    if sc < 0:
        L.append('AVISO: SC negativo: a la salida del condensador no hay líquido solo (burbujas en el visor) o la medición está mal hecha.')
    candidatos = []
    for nombre, req, req_p, necesita_p, revisar in PATRONES:
        if not all(ev[k] in v for k, v in req.items()):
            continue
        if not all(pres[k] in v for k, v in req_p.items() if k in pres):
            continue
        faltan = [k for k in req_p if k not in pres]
        if faltan and necesita_p:
            continue    # sin el dato de presion este patron no se puede proponer
        candidatos.append((nombre, revisar, faltan))
    L.append('Lectura orientativa:')
    if not candidatos:
        if ev['sh'] == 'normal' and ev['sc'] == 'normal' and all(v == 'normal' for v in pres.values()):
            L.append('  valores dentro de los rangos orientativos: buscar la falla en otro lado (eléctrica, control, aire).')
        else:
            L.append('  sin un patrón claro: repetir las mediciones con el equipo estable y comparar con la tabla de síntomas.')
    for nombre, revisar, faltan in candidatos:
        L.append('  - compatible con %s%s. Qué hacer: %s.' % (nombre, (' (falta --%s para confirmarlo)' % ' y --'.join(
            {'alta': 'tamb', 'baja': 'tinterior'}[f] for f in faltan)) if faltan else '', revisar))
    L.append('La lectura orienta; el diagnóstico se confirma con corriente del compresor, temperaturas de aire y una inspección.')
    return {'te': te_r, 'tc': tc_b, 'sh': sh, 'sc': sc, 'ev': ev, 'pres': pres, 'candidatos': [c[0] for c in candidatos]}, L


# ------------------------------------------------------------------------------------------ ciclo
def ciclo(R, tevap, tcond, sh, sc, Q, eta=None):
    if tcond < tevap + 10:
        raise ValueError('la condensación tiene que estar al menos 10 K arriba de la evaporación')
    if Q <= 0:
        raise ValueError('la capacidad tiene que ser positiva (kW)')
    if eta is not None and not 0.3 <= eta <= 1:
        raise ValueError('el rendimiento isentrópico va de 0,3 a 1')
    pe, pc = R.p_rocio(tevap), R.p_rocio(tcond)
    h1, s1, v1 = R.vapor(tevap, sh)
    tbc = R.t_burbuja(pc)
    humedo = s1 < R.s_vap(tcond)
    if humedo:   # fluido "seco" (R-600a): la compresion isentropica termina en vapor humedo
        x = (s1 - R.s_liq(tbc)) / (R.s_vap(tcond) - R.s_liq(tbc))
        h2s, t2s = R.h_liq(tbc) + x * (R.h_vap(tcond) - R.h_liq(tbc)), tcond
    else:
        x = 1.0
        t2s = tcond + R.sh_de_s(tcond, s1)
        h2s = R.vapor(tcond, t2s - tcond)[0]
    t3 = tbc - sc
    h3 = R.h_subenfriado(tbc, sc)
    tbe = R.t_burbuja(pe)
    x4 = (h3 - R.h_liq(tbe)) / (R.h_vap(tevap) - R.h_liq(tbe))
    qe, ws = h1 - h3, h2s - h1
    m = Q / qe
    r = {'pe': pe, 'pc': pc, 'h1': h1, 's1': s1, 'v1': v1, 't1': tevap + sh, 'h2s': h2s, 't2s': t2s, 'tbc': tbc,
         't3': t3, 'h3': h3, 'x4': x4, 'qe': qe, 'ws': ws, 'm': m, 'Ps': m * ws, 'COPs': qe / ws, 'rc': pc / pe,
         'Vasp': m * v1 * 3600, 'qv': qe / v1, 'carnot': (tevap + K) / (tcond - tevap), 'humedo': humedo, 'x2s': x, 'eta': eta,
         't4': tbe + x4 * (tevap - tbe)}
    eta_ = eta or 1.0
    h2 = h1 + ws / eta_
    r['h2'] = h2
    r['P'] = r['Ps'] / eta_
    r['COP'] = qe / (ws / eta_)
    r['t2'] = tcond + R.sh_de_h(tcond, h2) if h2 > R.h_vap(tcond) else tcond
    r['Qc'] = m * (h2 - h3)
    return r


