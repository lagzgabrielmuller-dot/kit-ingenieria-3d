def main(argv=None):
    a = construir_parser().parse_args(argv)
    try:
        if a.cmd == 'demo':
            return cmd_demo()
        if a.cmd == 'convertir':
            _, L = convertir(a.valor, a.de)
        elif a.cmd == 'info':
            L = info(refrigerante(a.ref) if a.ref else None)
        elif a.cmd == 'carga':
            r = carga(a.largo, a.ancho, a.alto, a.text, a.hrext, a.tint, a.hrint, a.superficie, a.ventana, a.renovaciones,
                      a.aire_exterior, a.personas, a.actividad, a.iluminacion, a.equipos, a.margen)
            L = informe_carga(r, a)
        else:
            R = refrigerante(a.ref)
            if a.cmd == 'saturacion':
                _, L = saturacion(R, a.t, a.p, a.unidad, a.absoluta, a.patm)
            elif a.cmd == 'tabla':
                _, L = tabla(R, a.desde, a.hasta, a.paso, a.md, a.patm)
            elif a.cmd == 'diagnostico':
                _, L = diagnostico(R, a.pbaja, a.palta, a.tsuccion, a.tliquido, a.unidad, a.patm, a.tamb, a.tinterior,
                                   a.expansion, a.sh_objetivo, a.sc_objetivo)
            elif a.cmd == 'ciclo':
                r = ciclo(R, a.tevap, a.tcond, a.sh, a.sc, a.capacidad, a.eta)
                L = informe_ciclo(R, r, a.tevap, a.tcond, a.sh, a.sc, a.capacidad)
            else:
                _, L = adicional(R, a.largo, a.precarga, a.gpm, a.diametro, a.espesor, a.tliq)
    except ValueError as ex:
        print('refrigeracion.py: %s' % ex, file=sys.stderr)
        return 2
    print('\n'.join(L))
    return 0


if __name__ == '__main__':
    try:
        sys.stdout.reconfigure(errors='replace')
    except (AttributeError, ValueError):
        pass
    sys.exit(main())
