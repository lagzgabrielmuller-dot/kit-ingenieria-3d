# Calor de las personas por actividad, W por persona (sensible, latente): ASHRAE Handbook Fundamentals 2017, cap. 18,
# tabla 1 (valores ajustados para un grupo de hombres, mujeres y niños). Verificar en la edicion consultada.
ACTIVIDAD = {'reposo': (65, 30, 'sentado en reposo (teatro, cine)'),
             'oficina': (70, 45, 'sentado, trabajo muy liviano (oficina, aula)'),
             'comercio': (75, 55, 'de pie, trabajo liviano o caminando despacio (comercio)'),
             'banco': (80, 140, 'trabajo liviano en banco de taller'),
             'pesado': (170, 255, 'trabajo pesado (taller)')}
RHO_AIRE = 1.2   # kg/m3, aire "estandar" (aire seco a 20 C y 101,325 kPa: 1,204 kg/m3)


def p_ws(t):
    """Presion de saturacion del agua en kPa sobre agua liquida, Hyland y Wexler (ASHRAE 2017, cap. 1). Ver secado-y-psicrometria."""
    T = t + K
    return math.exp(-5.8002206e3 / T + 1.3914993 - 4.8640239e-2 * T + 4.1764768e-5 * T ** 2
                    - 1.4452093e-8 * T ** 3 + 6.5459673 * math.log(T)) / 1000


def w_aire(t, hr, p=101.325):
    pw = hr / 100 * p_ws(t)
    return 0.621945 * pw / (p - pw)


def leer_campos(txt, minimo, maximo, que):
    partes = [x.strip() for x in txt.split(';')]
    if not minimo <= len(partes) <= maximo:
        raise ValueError('%s: «%s» tiene que tener entre %d y %d campos separados por ;' % (que, txt, minimo, maximo))
    nombre = partes[0]
    try:
        vals = [float(x.replace(',', '.')) for x in partes[1:]]
    except ValueError:
        raise ValueError('%s: «%s» tiene un número mal escrito' % (que, txt))
    return nombre, vals


def carga(largo, ancho, alto, text=35.0, hrext=40.0, tint=24.0, hrint=50.0, superficies=(), ventanas=(),
          renovaciones=0.0, aire_ext=0.0, personas=0, actividad='oficina', iluminacion=0.0, equipos=0.0, margen=0.0):
    if min(largo, ancho, alto) <= 0:
        raise ValueError('largo, ancho y alto tienen que ser positivos')
    if actividad not in ACTIVIDAD:
        raise ValueError('--actividad: %s' % ', '.join(ACTIVIDAD))
    S, V, dT = largo * ancho, largo * ancho * alto, text - tint
    comp = []    # (rubro, detalle, Qs, Ql)
    for txt in superficies:
        nombre, v = leer_campos(txt, 3, 4, '--superficie')
        U, A = v[0], v[1]
        extra = v[2] if len(v) > 2 else 0.0
        q = U * A * (dT + extra)
        if extra:
            det = 'U·A·(ΔT + ΔTsol) = %s·%s·(%s + %s)' % (n(U, 2), n(A, 2), n(dT, 1), n(extra, 1))
        else:
            det = 'U·A·ΔT = %s·%s·%s' % (n(U, 2), n(A, 2), n(dT, 1))
        comp.append(('Transmisión: ' + nombre, det, q, 0.0))
    for txt in ventanas:
        nombre, v = leer_campos(txt, 5, 5, '--ventana')
        A, U, FS, I = v
        comp.append(('Vidrio (transmisión): ' + nombre, 'U·A·ΔT = %s·%s·%s' % (n(U, 2), n(A, 2), n(dT, 1)), U * A * dT, 0.0))
        comp.append(('Vidrio (radiación): ' + nombre, 'A·FS·I = %s·%s·%s' % (n(A, 2), n(FS, 2), n(I, 0)), A * FS * I, 0.0))
    Vdot = renovaciones * V / 3600 + aire_ext / 3600      # m3/s
    if Vdot > 0:
        we, wi = w_aire(text, hrext), w_aire(tint, hrint)
        qs = RHO_AIRE * Vdot * (1006 + 1860 * we) * dT
        ql = RHO_AIRE * Vdot * (2501e3 + 1860 * tint) * (we - wi)
        det = '%s m³/h; ρ·V·(1006 + 1860·We)·ΔT y ρ·V·(2 501 000 + 1860·ti)·(We − Wi), We = %s, Wi = %s g/kg' % (
            n(Vdot * 3600, 0), n(1000 * we, 2), n(1000 * wi, 2))
        comp.append(('Aire exterior (infiltración y ventilación)', det, qs, max(ql, 0.0)))
    if personas:
        qs1, ql1, desc = ACTIVIDAD[actividad]
        comp.append(('Personas', '%d · (%d + %d) W, %s' % (personas, qs1, ql1, desc), personas * qs1, personas * ql1))
    if iluminacion:
        comp.append(('Iluminación', 'potencia instalada', iluminacion, 0.0))
    if equipos:
        comp.append(('Equipos', 'potencia en uso', equipos, 0.0))
    Qs, Ql = sum(c[2] for c in comp), sum(c[3] for c in comp)
    Qt = Qs + Ql
    Qd = Qt * (1 + margen / 100)
    return {'S': S, 'V': V, 'comp': comp, 'Qs': Qs, 'Ql': Ql, 'Qt': Qt, 'Qd': Qd, 'fcs': Qs / Qt if Qt else 0.0,
            'margen': margen, 'Vdot': Vdot}


