def pulgadas(txt):
    txt = txt.strip().replace('"', '').replace(',', '.')
    if '/' in txt:
        a, b = txt.split('/')
        return float(a) / float(b)
    return float(txt)


def adicional(R, largo, precarga, gpm=None, diametro=None, espesor=0.8, tliq=35.0):
    extra = largo - precarga
    L, r = [], {}
    if gpm is None:
        if diametro is None:
            raise ValueError('indicar --gpm (dato del fabricante) o --diametro de la línea de líquido para estimarlo')
        de = pulgadas(diametro) * 25.4
        di = de - 2 * espesor
        if di <= 0:
            raise ValueError('espesor demasiado grande para ese diámetro')
        gpm = R.rho_liq(tliq) * math.pi * (di / 1000) ** 2 / 4 * 1000
        L.append('Estimación: la línea de líquido de %s" (%s mm, espesor %s mm, interior %s mm) llena de %s líquido a %s °C '
                 '(%s kg/m³) contiene ρ·π·di²/4 = %s g/m. Manda el dato del manual del equipo.'
                 % (diametro, n(de, 2), n(espesor, 2), n(di, 2), R.nombre, n(tliq, 0), n(R.rho_liq(tliq), 0), n(gpm, 1)))
    r['gpm'] = gpm
    if extra <= 0:
        r['m'] = 0.0
        L.append('Cañería de %s m ≤ %s m precargados: no hace falta carga adicional (si es mucho más corta, ver el manual).'
                 % (n(largo, 1), n(precarga, 1)))
    else:
        r['m'] = extra * gpm
        L.append('Carga adicional = (L − L precarga)·g/m = (%s − %s)·%s = %s g de %s, por peso y %s'
                 % (n(largo, 1), n(precarga, 1), n(gpm, 1), n(r['m'], 0), R.nombre,
                    'en fase líquida (mezcla)' if R.info['mezcla'] else 'como indique el fabricante'))
    return r, L


UNIDADES = {'w': 1.0, 'kw': 1000.0, 'frig': W_POR_FRIG, 'kcal': W_POR_FRIG, 'btu': W_POR_BTUH, 'tr': W_POR_TR}


def convertir(valor, de):
    clave = de.lower().replace('/h', '')
    if clave not in UNIDADES:
        raise ValueError('--de: W, kW, frig (frigorías/h = kcal/h), btu (BTU/h) o tr')
    W = valor * UNIDADES[clave]
    return W, [potencias(W)]


